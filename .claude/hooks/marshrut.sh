#!/bin/bash
# Подсказка-маршрут на каждое сообщение: режим студии + кого позвали по имени + горячий навык.
# Это намёк помощнику, не приказ: совпадение случайное — действуй по смыслу.

DIR="${CLAUDE_PROJECT_DIR:-$(pwd)}"
cd "$DIR" || exit 0
export LC_ALL=en_US.UTF-8
IN=$(cat)
P=$(printf '%s' "$IN" | tr '[:upper:]АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ' '[:lower:]абвгдеёжзийклмнопрстуфхцчшщъыьэюя')

MODE="учёба"
grep -qi '^Режим: работа' studio/ucheba.md 2>/dev/null && MODE="работа"

has() { printf '%s' "$P" | grep -qE "$1"; }

# Имена
if has '"prompt": *"[^"]{0,3}(директор)'; then
  echo "[маршрут] позвали Директора → team/direktor/core.md"
elif has '"prompt": *"[^"]{0,3}(господин тимур|учитель|тимур)'; then
  if [ "$MODE" = "работа" ]; then
    echo "[маршрут] позвали учителя, но владелица уже выпущена. Отвечает Директор: «Господин Тимур тебя выпустил, теперь я с тобой — спрашивай что угодно» — и помогает сам."
  else
    echo "[маршрут] Господин Тимур → team/uchitel/core.md"
  fi
fi

# Горячие намерения
if has 'instagram\.com|youtu\.?be|tiktok\.com'; then echo "[маршрут] ссылка на ролик → навык razvedchik"; fi
if has 'застрял|не работает|не понимаю|ничего не понятно|сломал|помоги'; then echo "[маршрут] → навык zastryala (спокойно, 1 вопрос, 1 шаг)"; fi
if has 'разбер[иу] стиль|паспорт стил|насмотренн|изучи (мои )?ролик'; then echo "[маршрут] → навык nasmotrennost"; fi
if has 'собери ролик|смонтируй|сделай ролик|в стиле клиента|монтаж ролик'; then echo "[маршрут] → навык montazh"; fi
if has 'новый клиент|пакет на месяц|что по клиентам'; then echo "[маршрут] → навык klienty"; fi
if has 'правки'; then echo "[маршрут] → навык pravki"; fi
if has 'хочу сотрудника|кого можно нанять|что (ещё |еще )?умеешь|нанять'; then echo "[маршрут] → навык najm"; fi
if has 'ключ|\.env|сейф|api'; then echo "[маршрут] → навык klyuchi (ключ в чат НЕ просить)"; fi
if has 'установ|постав[иь]|не установлено'; then echo "[маршрут] → навык ustanovka"; fi
if has 'обнови офис'; then echo "[маршрут] → навык obnovit"; fi

# Защита: похоже, в сообщении ключ
if printf '%s' "$IN" | grep -qE '"prompt": *"[^"]*([A-Za-z0-9]{32,}|AIza[0-9A-Za-z_-]{20,}|sk-[A-Za-z0-9]{20,})'; then
  echo "[безопасность] ⚠️ похоже, в сообщении ключ. НЕ повторяй его. Спокойно объясни: ключи только в сейф .env; этот лучше удалить на сайте сервиса и сделать новый (навык klyuchi)."
fi
exit 0
